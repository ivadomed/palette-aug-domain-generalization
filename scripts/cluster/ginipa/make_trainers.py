#!/usr/bin/env python
"""Generate the per-dataset GIN-IPA trainer classes and their ADDITIVE registration shims (ginipa arm, 2026-11-01).

For each of the 9 trainable datasets of the paper's main table:
  <pkg>/trainers/ginipa.py              class nnUNetTrainer<DS>GinIpa(nnUNetTrainer<DS>Base, nnUNetTrainerDAExtGPUGinIpa)
  02_nnunet/<DS>GinIpaTrainers.py       NEW registration shim (copied into each cluster's venv nnunetv2/training/nnUNetTrainer/)

Why a separate shim and not one more import line in <DS>Trainers.py / trainers/__init__.py: the GinIpa base class
(auglab.trainers.nnUNetTrainerDAExtGPUGinIpa) exists ONLY in the GIN-IPA AugLab pin (scripts/cluster/ginipa/PIN.conf), not in
the shared AugLab trees. The existing shims import all their classes in ONE try block, so a failing GinIpa import there would
silently de-register every trainer of that dataset for every other job. The new shim is a strict no-op (no import, no sys.path
change, no output) unless a directory on sys.path contains auglab/trainers/nnUNetTrainerDAExtGPUGinIpa.py (i.e. the pin is on
PYTHONPATH, which only the ginipa job bodies / predict wrappers do); then it imports the dataset's GinIpa class in its own try
block and prints where the GinIpa code came from (the in-job proof that the pin is what runs).

MRO of every class: <DS>GinIpa -> <DS>Base (do_split anti-contamination guard) -> nnUNetTrainerFast (seed, epochs, TF32, WandB)
  -> nnUNetTrainerDAExtGPUGinIpa (3 GIN/IPA copies, KL consistency) -> nnUNetTrainerDAExtGPU -> nnUNetTrainer
(the same position nnUNetTrainerDAExtGPU has in every <DS>AugLabDefault, e.g. the SRCSM competitor's trainer). Nothing defaults
AUGLAB_PARAMS_GPU_JSON to default01-23 (check B in NOTES_trainer.md): the wrappers export the pin's GIN-IPA config, and the GinIpa
trainer itself falls back to that config when the variable is unset.
  python scripts/cluster/ginipa/make_trainers.py [--check]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
T = "benchmark/02_tasks"
# dataset dir | python package | dir holding the package's trainers/ (relative to 5_scripts_<ds>) | class infix | shim prefix
DS = [
    ("brain_tumor/brats2024-glioma", "brats2024_glioma", "02_nnunet", "BraTS2024Glioma", "BraTS2024Glioma"),
    ("abdomen_healthy/chaos", "chaos", "02_nnunet", "CHAOS", "CHAOS"),
    ("brain_healthy/on-harmony", "on_harmony", "on_harmony", "OnHarmony", "OnHarmony"),
    ("brain_ms/open-ms", "open_ms", "open_ms", "OpenMS", "OpenMS"),
    ("mandible_healthy/toothfairy2", "toothfairy2", "toothfairy2", "ToothFairy2", "ToothFairy2"),
    ("breast_cancer/ispy2", "ispy2", "ispy2", "ISPY2", "ISPY2"),
    ("pelvis_healthy/totalseg-pelvic", "totalseg_pelvic", "totalseg_pelvic", "TotalsegPelvic", "TotalsegPelvic"),
    ("liver_hcc/atlas-liver-hcc", "atlas_liver_hcc", "atlas_liver_hcc", "AtlasLiverHCC", "AtlasLiverHCC"),
    ("pancreas_disease/pansegdata", "pansegdata", "pansegdata", "PANSEGDATA", "PANSEGDATA"),
]

TRAINER = '''"""
nnUNetTrainer{inf}GinIpa -- GIN-IPA competitor arm (ginipa) for {name}.
GENERATED by scripts/cluster/ginipa/make_trainers.py (do not hand-edit).

GIN-IPA: Ouyang et al., "Causality-inspired single-source domain generalization for medical image segmentation", IEEE TMI 2023
(arXiv 2111.12525), ported into AugLab on branch gin-ipa (auglab/trainers/nnUNetTrainerDAExtGPUGinIpa.py,
auglab/transforms/gpu/gin_ipa.py; MIT-licensed original code, notice in those files).

MRO: nnUNetTrainer{inf}GinIpa
  -> nnUNetTrainer{inf}Base        (do_split -- anti-contamination guard)
  -> nnUNetTrainerFast             (seed, epochs, TF32, WandB hooks)
  -> nnUNetTrainerDAExtGPUGinIpa   (3 GIN/IPA copies per step, seg loss on copy 1 + 10 x KL consistency)
  -> nnUNetTrainerDAExtGPU         (GPU spatial transforms from AUGLAB_PARAMS_GPU_JSON)
  -> nnUNetTrainer
Same place in the MRO as nnUNetTrainerDAExtGPU in nnUNetTrainer{inf}AugLabDefault (the SRCSM / SynthSeg competitors' trainer).

The GinIpa base class exists ONLY in the GIN-IPA AugLab pin (scripts/cluster/ginipa/PIN.conf). Import this module only through
02_nnunet/{shim}GinIpaTrainers.py (never from trainers/__init__.py or {shim}Trainers.py). AUGLAB_PARAMS_GPU_JSON is deliberately NOT
defaulted here: the wrapper exports the pin's GIN-IPA config; unset, the GinIpa trainer defaults to its own config.
"""
from auglab.trainers.nnUNetTrainerDAExtGPUGinIpa import nnUNetTrainerDAExtGPUGinIpa

from {pkg}.trainers.base import nnUNetTrainer{inf}Base


class nnUNetTrainer{inf}GinIpa(nnUNetTrainer{inf}Base, nnUNetTrainerDAExtGPUGinIpa):
    """GIN-IPA training for {name}; validation on clean data (inherited)."""

    validation_uses_augmentation: bool = False
{extra}'''

EXTRA = '''

class nnUNetTrainer{inf}{c}GinIpa(nnUNetTrainer{inf}GinIpa):
    """{c} binding: identical logic, only the trainer name differs (as nnUNetTrainer{inf}{c}AugLabDefault)."""
    pass
'''

SHIM = '''# Registration shim for the GIN-IPA arm (ginipa) -- ADDITIVE, separate from {shim}Trainers.py so no existing result-producing
# registration file is touched. GENERATED by scripts/cluster/ginipa/make_trainers.py (do not hand-edit). Copy it next to the other
# shims after every fresh venv/nnunetv2 install (the venv setup's `find ... '*Trainers.py'` picks it up):
#   cp benchmark/02_tasks/{dsdir}/5_scripts_{dsname}/02_nnunet/{shim}GinIpaTrainers.py \\
#      .venv/lib/python3.*/site-packages/nnunetv2/training/nnUNetTrainer/
"""
Makes nnUNetTrainer{inf}GinIpa discoverable by nnU-Net -- ONLY when the GIN-IPA AugLab pin is on sys.path.

nnU-Net's recursive_find_python_class imports every module of training/nnUNetTrainer/ while it searches, in every training and
prediction job on this venv. Without the pin (all non-ginipa jobs) this module does nothing: no import, no sys.path change, no output.
With the pin (a directory on sys.path holding auglab/trainers/nnUNetTrainerDAExtGPUGinIpa.py: the ginipa job bodies put it first on
PYTHONPATH) it adds the dataset's script dirs exactly as {shim}Trainers.py does, imports the class in its own try block, and prints
where the GinIpa code was imported from.
"""
import os
import sys

_pin = next((p for p in sys.path if p and os.path.isfile(os.path.join(p, "auglab", "trainers", "nnUNetTrainerDAExtGPUGinIpa.py"))), None)
if _pin is not None:
    _root = os.environ.get("NNUNET_PROJECT_ROOT", "")
    if _root:
        _scripts = os.path.join(_root, "benchmark", "02_tasks", "{dsdir_a}", "{dsdir_b}", "5_scripts_{dsname}")
        for _p in (_root, _scripts):
            if _p and _p not in sys.path:
                sys.path.insert(0, _p)
    try:
        from {pkg}.trainers.ginipa import (  # noqa: F401
            nnUNetTrainer{inf}GinIpa,{extra_imports}
        )
        import auglab.trainers.nnUNetTrainerDAExtGPUGinIpa as _gi
        import auglab.transforms.gpu.gin_ipa as _gt
        print(f"[{shim}GinIpaTrainers] nnUNetTrainer{inf}GinIpa registered; pin on sys.path: {{_pin}}; "
              f"GinIpa trainer from {{_gi.__file__}}; GinIpaGPU from {{_gt.__file__}}", flush=True)
    except Exception as _e:  # pragma: no cover -- discovery must not hard-crash nnU-Net import
        print(f"[{shim}GinIpaTrainers] import failed: {{_e!r}}", flush=True)
'''


# extra thin per-contrast bindings (brats names its trainers per contrast: <DS>T2wAugLabDefault(<DS>AugLabDefault), same logic)
EXTRA_CONTRASTS = {"BraTS2024Glioma": ["T2w", "T2f", "T1c"]}


def outputs():
    for dsdir, pkg, pkgparent, inf, shim in DS:
        dsname = Path(dsdir).name
        sd = ROOT / T / dsdir / f"5_scripts_{dsname}"
        a, b = dsdir.split("/")
        ex = EXTRA_CONTRASTS.get(inf, [])
        extra = "".join(EXTRA.format(inf=inf, c=c) for c in ex)
        yield sd / pkgparent / "trainers" / "ginipa.py", TRAINER.format(inf=inf, name=dsname, pkg=pkg, shim=shim, extra=extra)
        imps = "".join(f"\n            nnUNetTrainer{inf}{c}GinIpa," for c in ex)
        yield sd / "02_nnunet" / f"{shim}GinIpaTrainers.py", SHIM.format(shim=shim, inf=inf, pkg=pkg, dsdir=dsdir, dsname=dsname,
                                                                         dsdir_a=a, dsdir_b=b, extra_imports=imps)


def main():
    check = "--check" in sys.argv
    bad = 0
    for p, text in outputs():
        if not (p.parent / "base.py").exists() and p.name == "ginipa.py":
            raise SystemExit(f"no base.py next to {p}")
        if check:
            ok = p.exists() and p.read_text() == text
            bad += not ok
            print(("OK   " if ok else "DIFF ") + str(p.relative_to(ROOT)))
        else:
            if p.exists() and p.read_text() != text:
                raise SystemExit(f"{p} exists with different content")
            p.write_text(text)
            print("wrote", p.relative_to(ROOT))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
