#!/usr/bin/env python
"""Generate the per-dataset SLAug trainer classes and their ADDITIVE registration shims (slaug arm, 2026-11-13; clone of scripts/cluster/ginipa/make_trainers.py).

For each of the 9 trainable datasets of the paper's main table:
  <pkg>/trainers/slaug.py              class nnUNetTrainer<DS>SLAug(nnUNetTrainer<DS>Base, nnUNetTrainerDAExtGPUSLAug)
  02_nnunet/<DS>SLAugTrainers.py       NEW registration shim (copied into each cluster's venv nnunetv2/training/nnUNetTrainer/)

Why a separate shim and not one more import line in <DS>Trainers.py / trainers/__init__.py: the SLAug base class
(auglab.trainers.nnUNetTrainerDAExtGPUSLAug) exists ONLY in the SLAug AugLab pin (scripts/cluster/slaug/PIN.conf), not in
the shared AugLab trees. The existing shims import all their classes in ONE try block, so a failing SLAug import there would
silently de-register every trainer of that dataset for every other job. The new shim is a strict no-op (no import, no sys.path
change, no output) unless a directory on sys.path contains auglab/trainers/nnUNetTrainerDAExtGPUSLAug.py (i.e. the pin is on
PYTHONPATH, which only the slaug job bodies / predict wrappers do); then it imports the dataset's SLAug class in its own try
block and prints where the SLAug code came from (the in-job proof that the pin is what runs).

MRO of every class: <DS>SLAug -> <DS>Base (do_split anti-contamination guard) -> nnUNetTrainerFast (seed, epochs, TF32, WandB)
  -> nnUNetTrainerDAExtGPUSLAug (GLA + LLA views, saliency-balancing fusion, 2 forward/backward per step) -> nnUNetTrainerDAExtGPU -> nnUNetTrainer
(the same position nnUNetTrainerDAExtGPU has in every <DS>AugLabDefault, e.g. the SRCSM competitor's trainer). Nothing defaults
AUGLAB_PARAMS_GPU_JSON to default01-23 (check B in NOTES_trainer.md): the wrappers export the pin's SLAug config, and the SLAug
trainer itself falls back to that config when the variable is unset.
  python scripts/cluster/slaug/make_trainers.py [--check]
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
T = "benchmark/02_tasks"
# dataset dir | python package | dir holding the package's trainers/ (relative to 5_scripts_<ds>) | class infix | shim prefix
DS = [
    ("brain_tumor/brats2024-glioma", "brats2024_glioma", "02_nnunet", "BraTS2024Glioma", "BraTS2024Glioma"),
    ("abdomen_healthy/chaos", "chaos", "02_nnunet", "CHAOS", "CHAOS"),
    ("brain_healthy/on-harmony", "on_harmony", "on_harmony", "OnHarmony", "OnHarmony"),
    ("brain_ms/open-ms", "open_ms", "open_ms", "OpenMS", "OpenMS"),
    ("mandible_healthy/toothfairy2", "toothfairy2", "toothfairy2", "ToothFairy2", "ToothFairy2"),
    ("breast_cancer/ispy2", "ispy2", "ispy2", "ISPY2", "ISPY2"),
    ("pelvis_healthy/totalseg-pelvic", "totalseg_pelvic", "totalseg_pelvic", "TotalsegPelvic", "TotalsegPelvic"),
    ("liver_hcc/atlas-liver-hcc", "atlas_liver_hcc", "atlas_liver_hcc", "AtlasLiverHCC", "AtlasLiverHCC"),
    ("pancreas_disease/pansegdata", "pansegdata", "pansegdata", "PANSEGDATA", "PANSEGDATA"),
]

TRAINER = '''"""
nnUNetTrainer{inf}SLAug -- SLAug competitor arm (slaug) for {name}.
GENERATED by scripts/cluster/slaug/make_trainers.py (do not hand-edit).

SLAug: Su et al., "Rethinking Data Augmentation for Single-source Domain Generalization in Medical Image Segmentation",
AAAI 2023 (arXiv 2211.14805), ported into AugLab on branch slaug (auglab/trainers/nnUNetTrainerDAExtGPUSLAug.py,
auglab/transforms/gpu/slaug.py; Apache-2.0 original code, notice in those files).

MRO: nnUNetTrainer{inf}SLAug
  -> nnUNetTrainer{inf}Base        (do_split -- anti-contamination guard)
  -> nnUNetTrainerFast             (seed, epochs, TF32, WandB hooks)
  -> nnUNetTrainerDAExtGPUSLAug   (GLA pass + SBF-fused pass, losses accumulated, one step)
  -> nnUNetTrainerDAExtGPU         (GPU spatial transforms from AUGLAB_PARAMS_GPU_JSON)
  -> nnUNetTrainer
Same place in the MRO as nnUNetTrainerDAExtGPU in nnUNetTrainer{inf}AugLabDefault (the SRCSM / SynthSeg competitors' trainer).

The SLAug base class exists ONLY in the SLAug AugLab pin (scripts/cluster/slaug/PIN.conf). Import this module only through
02_nnunet/{shim}SLAugTrainers.py (never from trainers/__init__.py or {shim}Trainers.py). AUGLAB_PARAMS_GPU_JSON is deliberately NOT
defaulted here: the wrapper exports the pin's SLAug config; unset or empty, the SLAug trainer defaults to its own config.
"""
from auglab.trainers.nnUNetTrainerDAExtGPUSLAug import nnUNetTrainerDAExtGPUSLAug

from {pkg}.trainers.base import nnUNetTrainer{inf}Base


class nnUNetTrainer{inf}SLAug(nnUNetTrainer{inf}Base, nnUNetTrainerDAExtGPUSLAug):
    """SLAug training for {name}; validation on clean data (inherited)."""

    validation_uses_augmentation: bool = False
{extra}'''

EXTRA = '''

class nnUNetTrainer{inf}{c}SLAug(nnUNetTrainer{inf}SLAug):
    """{c} binding: identical logic, only the trainer name differs (as nnUNetTrainer{inf}{c}AugLabDefault)."""
    pass
'''

SHIM = '''# Registration shim for the SLAug arm (slaug) -- ADDITIVE, separate from {shim}Trainers.py so no existing result-producing
# registration file is touched. GENERATED by scripts/cluster/slaug/make_trainers.py (do not hand-edit). Copy it next to the other
# shims after every fresh venv/nnunetv2 install (the venv setup's `find ... '*Trainers.py'` picks it up):
#   cp benchmark/02_tasks/{dsdir}/5_scripts_{dsname}/02_nnunet/{shim}SLAugTrainers.py \\
#      .venv/lib/python3.*/site-packages/nnunetv2/training/nnUNetTrainer/
"""
Makes nnUNetTrainer{inf}SLAug discoverable by nnU-Net -- ONLY when the SLAug AugLab pin is on sys.path.

nnU-Net's recursive_find_python_class imports every module of training/nnUNetTrainer/ while it searches, in every training and
prediction job on this venv. Without the pin (all non-slaug jobs) this module does nothing: no import, no sys.path change, no output.
With the pin (a directory on sys.path holding auglab/trainers/nnUNetTrainerDAExtGPUSLAug.py: the slaug job bodies put it first on
PYTHONPATH) it adds the dataset's script dirs exactly as {shim}Trainers.py does, imports the class in its own try block, and prints
where the SLAug code was imported from.
"""
import os
import sys

_pin = next((p for p in sys.path if p and os.path.isfile(os.path.join(p, "auglab", "trainers", "nnUNetTrainerDAExtGPUSLAug.py"))), None)
if _pin is not None:
    _root = os.environ.get("NNUNET_PROJECT_ROOT", "")
    if _root:
        _scripts = os.path.join(_root, "benchmark", "02_tasks", "{dsdir_a}", "{dsdir_b}", "5_scripts_{dsname}")
        for _p in (_root, _scripts):
            if _p and _p not in sys.path:
                sys.path.insert(0, _p)
    try:
        from {pkg}.trainers.slaug import (  # noqa: F401
            nnUNetTrainer{inf}SLAug,{extra_imports}
        )
        import auglab.trainers.nnUNetTrainerDAExtGPUSLAug as _gi
        import auglab.transforms.gpu.slaug as _gt
        print(f"[{shim}SLAugTrainers] nnUNetTrainer{inf}SLAug registered; pin on sys.path: {{_pin}}; "
              f"SLAug trainer from {{_gi.__file__}}; SLAugGPU from {{_gt.__file__}}", flush=True)
    except Exception as _e:  # pragma: no cover -- discovery must not hard-crash nnU-Net import
        print(f"[{shim}SLAugTrainers] import failed: {{_e!r}}", flush=True)
'''


# extra thin per-contrast bindings (brats names its trainers per contrast: <DS>T2wAugLabDefault(<DS>AugLabDefault), same logic)
EXTRA_CONTRASTS = {"BraTS2024Glioma": ["T2w", "T2f", "T1c"]}


def outputs():
    for dsdir, pkg, pkgparent, inf, shim in DS:
        dsname = Path(dsdir).name
        sd = ROOT / T / dsdir / f"5_scripts_{dsname}"
        a, b = dsdir.split("/")
        ex = EXTRA_CONTRASTS.get(inf, [])
        extra = "".join(EXTRA.format(inf=inf, c=c) for c in ex)
        yield sd / pkgparent / "trainers" / "slaug.py", TRAINER.format(inf=inf, name=dsname, pkg=pkg, shim=shim, extra=extra)
        imps = "".join(f"\n            nnUNetTrainer{inf}{c}SLAug," for c in ex)
        yield sd / "02_nnunet" / f"{shim}SLAugTrainers.py", SHIM.format(shim=shim, inf=inf, pkg=pkg, dsdir=dsdir, dsname=dsname,
                                                                         dsdir_a=a, dsdir_b=b, extra_imports=imps)


def main():
    check = "--check" in sys.argv
    bad = 0
    for p, text in outputs():
        if not (p.parent / "base.py").exists() and p.name == "slaug.py":
            raise SystemExit(f"no base.py next to {p}")
        if check:
            ok = p.exists() and p.read_text() == text
            bad += not ok
            print(("OK   " if ok else "DIFF ") + str(p.relative_to(ROOT)))
        else:
            if p.exists() and p.read_text() != text:
                raise SystemExit(f"{p} exists with different content")
            p.write_text(text)
            print("wrote", p.relative_to(ROOT))
    sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
