#!/usr/bin/env python
"""Write the aggregation configs for PALETTE + REDUCED Auglab ("texlite") from the headline configs (Vulcan, after
scripts/cluster/fetch_texlite_metrics.sh). Each new config = the setting's headline config + the texlite run (+ PALETTE alone,
the val000 rung-5 run, in the per-setting table when its metrics are found), with an explicit output_dir in a `texlite/`
subdir so the headline tables are never overwritten. `sig. vs ref` stays the headline PALETTE-Aug run (the texlite METHOD does
not contain REF_SUBSTR; `sig. vs ref` is therefore the ONE-SIDED test "headline PALETTE-Aug better than this row" -- to test
"reduced set better", set sig_ref: <texlite run> in a scratch copy).
usage: python write_configs.py <run_ids.tsv> [<run_ids_2.tsv> ...]   (header + columns: setting, fold, run_id, pack, ...[, arm])
Arms: rows are grouped by (setting, arm); `arm` column optional (absent/empty = texlite). Every arm's run is appended to the SAME
per-setting/combined texlite config (texlite first, then texlite_keepres), so one table compares headline, PALETTE alone and both
reduced sets against the same reference."""
import glob, os, sys
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[3]
T = ROOT / "benchmark/02_tasks"
NEWM = "auglabAugTexlite_v26_6_2_train050_val000"
ARM_METHOD = {"texlite": NEWM, "keepres": "auglabAugTexliteKeepres_v26_6_2_train050_val000", "edgeonly": "auglabAugEdgeonly_v26_6_2_train050_val000"}
ARM_LABEL = {"texlite": "texlite", "keepres": "texlite_keepres", "edgeonly": "edgeonly"}
# setting -> (scripts dir, per-setting config, combined config or None, metrics dir for the PA-alone lookup)
# DEVELOPMENT settings only (2026-10-15 evening): glioma t1n, mandible cbct and HCC t1w are held out for the paper (their texlite /
# keepres runs were cancelled), so no texlite table is written for them; rows of those settings in the run tables are ignored.
S = {
    "onh_t1w": ("brain_healthy/on-harmony/5_scripts_on-harmony", "on-harmony_T1w.yaml", None,
                "brain_healthy/on-harmony/8_results_on-harmony/02_metrics/on_harmony_model/T1w"),
    "openms_flair": ("brain_ms/open-ms/5_scripts_open-ms", "open-ms_flair_01_results.yaml", None,
                     "brain_ms/open-ms/8_results_open-ms/02_metrics/open_ms_model/flair"),
    "chaos_t2spir": ("abdomen_healthy/chaos/5_scripts_chaos", "chaos_t2spir_01_results.yaml", None,
                     "abdomen_healthy/chaos/8_results_chaos/02_metrics/chaos_model/t2spir"),
}
HDR = ("# GENERATED by scripts/cluster/auglab_texlite/write_configs.py from {src} (do not hand-edit): the headline table + PALETTE\n"
       "# with a REDUCED Auglab set ({arms}){pa}; outputs in a texlite/ subdir, sig. vs ref = the headline PALETTE-Aug run.\n")


def pa_alone(mdir):
    """rung-5 'PALETTE alone' val000 run (flat or ablations/), as an aggregate run key; None if absent/ambiguous."""
    hits = []
    for sub in ("", "ablations/"):
        for p in glob.glob(str(T / mdir / sub / "*_v26_6_2_train050_val000_[0-9]*")):
            cat, rid = Path(p).name.split("_", 1)
            if cat not in ("auglab", "nnUNet"):
                continue
            if "auglabAug" in rid or "_pv_" in rid or rid.endswith(("_final", "_srcmatch")):
                continue
            # keep the category prefix: aggregate_from_config resolves "<prefix><key>" with prefixes nnUNet_/auglab_/"" on the
            # WHOLE key, so "ablations/<run>" never resolves ("auglab_ablations/..."), "ablations/<cat>_<run>" does (exact)
            hits.append(sub + (Path(p).name if sub else rid))
    return sorted(hits)[-1] if hits else None


def main():
    rid = {}   # setting -> arm -> {run ids}
    for f in sys.argv[1:]:
        lines = [l for l in Path(f).read_text().splitlines() if l.strip()]
        hdr = lines[0].split("\t") if lines and lines[0].startswith("setting\t") else []
        ai = hdr.index("arm") if "arm" in hdr else None
        for l in lines[1 if hdr else 0:]:
            c = l.split("\t")
            arm = (c[ai] if ai is not None and ai < len(c) else "") or "texlite"
            assert arm in ARM_METHOD, (f, arm)
            if c[0] in S:
                rid.setdefault(c[0], {}).setdefault(arm, set()).add(c[2])
    for s, (d, per, comb, mdir) in S.items():
        if s not in rid:
            print(f"[skip] {s}: no run id"); continue
        arms = [a for a in ARM_METHOD if a in rid[s]]
        for a in arms:
            assert len(rid[s][a]) == 1, (s, a, rid[s][a])
            assert ARM_METHOD[a] + "_" in next(iter(rid[s][a])), (s, a, rid[s][a])
        rr = [next(iter(rid[s][a])) for a in arms]
        lab = ", ".join(ARM_LABEL[a] for a in arms)
        cdir = T / d / "06_evaluate/configs"
        cfg = yaml.safe_load((cdir / per).read_text())
        pa = pa_alone(mdir)
        runs = list(cfg["runs"]) + ([pa] if pa and pa not in cfg["runs"] else []) + rr
        cfg["runs"] = runs
        cfg["title"] = cfg.get("title", per) + f" + PALETTE with reduced Auglab ({lab})"
        md = cfg["metrics_dir"]
        cfg["output_dir"] = md.rstrip("/") + "/texlite"
        out = cdir / (per.replace("_01_results.yaml", "_texlite_01_results.yaml") if per.endswith("_01_results.yaml") else per.replace(".yaml", "_texlite_01_results.yaml"))
        out.write_text(HDR.format(src=per, arms=lab, pa=" and PALETTE alone (val000 rung 5: " + pa + ")" if pa else "") + yaml.safe_dump(cfg, sort_keys=False, width=200, allow_unicode=True))
        print(f"[write] {out.relative_to(ROOT)}  runs={len(runs)}  arms={arms}  PA alone={pa}")
        if comb:
            c = yaml.safe_load((cdir / comb).read_text())
            assert len(c["modalities"]) == 1, comb
            for a, r in zip(arms, rr):
                c["modalities"][0]["runs"][ARM_METHOD[a]] = r
            c["output_dir"] = c["output_dir"].rstrip("/") + "/texlite"
            c["title"] = c.get("title", comb) + f" + PALETTE with reduced Auglab ({lab})"
            out = cdir / comb.replace("_01_results.yaml", "_texlite_01_results.yaml")
            out.write_text(HDR.format(src=comb, arms=lab, pa="") + yaml.safe_dump(c, sort_keys=False, width=200, allow_unicode=True))
            print(f"[write] {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
